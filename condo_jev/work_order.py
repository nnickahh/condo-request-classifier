def format_staff_dispatch_alert(wo: WorkOrder) -> str:
    """Format a clean, concise operational alert for estate staff without ML telemetry clutter."""
    alert_badge = "[URGENT EMERGENCY WORK ORDER]" if wo.priority == Priority.EMERGENCY else "[NEW WORK ORDER DISPATCH]"
    handle = f"@{wo.resident_username}" if wo.resident_username else f"User {wo.resident_id}"
    resident_info = f"{wo.resident_name} ({handle})" if wo.resident_name else handle
    loc = wo.location or "Pending location confirmation"

    lines = [
        f"*{alert_badge} — #{wo.work_order_id}*",
        "──────────────────────────────",
        f"• *Resident:* {resident_info}",
        f"• *Location:* `{loc}`",
        f"• *Team:* {wo.assigned_team}",
        f"• *Priority:* {wo.priority.value.upper()} (SLA: {wo.sla_target})",
    ]
    if wo.assigned_technician:
        contact = f" (`{wo.technician_phone}`)" if wo.technician_phone else ""
        lines.append(f"• *Assigned Tech:* {wo.assigned_technician}{contact}")
    if wo.photo_path:
        ext = Path(wo.photo_path).suffix.lower()
        media_type = "Voice/Audio Recording" if ext in (".ogg", ".oga", ".mp3", ".wav", ".m4a") else "Photo Evidence"
        lines.append(f"• *Attachment:* {media_type} (`{Path(wo.photo_path).name}`)")

    if wo.detected_language and wo.detected_language != "en" and wo.original_text and wo.original_text != wo.text:
        lines.append(f"\n*Original Report ({wo.detected_language.upper()}):*\n\"{wo.original_text}\"")
        lines.append(f"*English Translation:*\n\"{wo.text}\"")
    elif wo.is_transcribed_audio:
        lines.append(f"\n*Audio Transcript (English):*\n\"{wo.text}\"")
    else:
        lines.append(f"\n*Issue Report:*\n\"{wo.text}\"")
    return "\n".join(lines)


def dispatch_outbound_webhook(
    event_type: str,
    work_order_data: dict[str, Any] | WorkOrder,
    webhook_url: str | None = None,
    secret: str | None = None,
    timeout: float = 3.0,
) -> dict[str, Any]:
    """
    Deliver a work order event payload to an external CMMS/Helpdesk (Jira, ServiceNow, Slack, Zapier).
    Returns delivery result dict {"success": bool, "status_code": int | None, "error": str | None}.
    """
    url = webhook_url or os.getenv("WORK_ORDER_WEBHOOK_URL")
    if not url:
        return {"success": False, "status_code": None, "error": "No webhook URL configured"}

    payload = {
        "event": event_type,
        "timestamp": datetime.now(timezone.utc).isoformat(),
        "work_order": (
            work_order_data.model_dump()
            if hasattr(work_order_data, "model_dump")
            else work_order_data
        ),
    }

    import hashlib
    import hmac
    import urllib.error
    import urllib.request

    data_bytes = json.dumps(payload, ensure_ascii=False).encode("utf-8")
    req = urllib.request.Request(
        url,
        data=data_bytes,
        headers={"Content-Type": "application/json; charset=utf-8", "User-Agent": "Condo-Jev-CMMS/1.0"},
        method="POST",
    )
    sec = secret or os.getenv("WORK_ORDER_WEBHOOK_SECRET")
    if sec:
        sig = hmac.new(sec.encode("utf-8"), data_bytes, hashlib.sha256).hexdigest()
        req.add_header("X-Condo-Signature", f"sha256={sig}")

    try:
        with urllib.request.urlopen(req, timeout=timeout) as resp:
            return {"success": 200 <= resp.status < 300, "status_code": resp.status, "error": None}
    except urllib.error.HTTPError as exc:
        return {"success": False, "status_code": exc.code, "error": str(exc)}
    except Exception as exc:
        return {"success": False, "status_code": None, "error": str(exc)}


class WorkOrderStore:
    """Thread-safe persistent JSON store for work orders generated by the triage agent."""

    def __init__(self, file_path: str | Path | None = None, webhook_url: str | None = None):
        if file_path is None:
            env_override = os.getenv("CONDO_WORK_ORDERS_FILE")
            if env_override:
                self.file_path = Path(env_override)
            else:
                base_dir = Path(__file__).resolve().parent.parent
                self.file_path = base_dir / "data" / "work_orders.json"
        else:
            self.file_path = Path(file_path)
        self.webhook_url = webhook_url or os.getenv("WORK_ORDER_WEBHOOK_URL")
        self._lock = threading.Lock()
        self._ensure_storage()

    def _ensure_storage(self) -> None:
        self.file_path.parent.mkdir(parents=True, exist_ok=True)
        if not self.file_path.exists():
            self._write_records([])

    def _read_records(self) -> list[dict[str, Any]]:
        if not self.file_path.exists():
            return []
        try:
            with open(self.file_path, "r", encoding="utf-8") as f:
                data = json.load(f)
                return data if isinstance(data, list) else []
        except (json.JSONDecodeError, OSError):
            return []

    def _write_records(self, records: list[dict[str, Any]]) -> None:
        with open(self.file_path, "w", encoding="utf-8") as f:
            json.dump(records, f, indent=2, ensure_ascii=False)

    def _trigger_webhook_async(self, event_type: str, wo: WorkOrder) -> None:
        """Trigger non-blocking outbound webhook delivery."""
        if self.webhook_url or os.getenv("WORK_ORDER_WEBHOOK_URL"):
            th = threading.Thread(
                target=dispatch_outbound_webhook,
                args=(event_type, wo, self.webhook_url),
                daemon=True,
            )
            th.start()

    def _notify_resident_async(
        self,
        wo: WorkOrder,
        text: str,
        markup: dict[str, Any] | None = None,
    ) -> None:
        """Asynchronously dispatch push notification to resident on Telegram."""
        chat_id = wo.resident_chat_id or (
            wo.resident_id
            if (wo.resident_id.isdigit() or (wo.resident_id.startswith("-") and wo.resident_id[1:].isdigit()))
            else None
        )
        if not chat_id or wo.channel != "Telegram":
            return

        def _send() -> None:
            send_telegram_direct_message(chat_id=chat_id, text=text, reply_markup=markup)

        th = threading.Thread(target=_send, daemon=True)
        th.start()

    def _notify_staff_async(
        self,
        wo: WorkOrder,
        text: str,
        markup: dict[str, Any] | None = None,
    ) -> None:
        """Asynchronously dispatch alert to internal estate staff Telegram group."""
        staff_chat = os.getenv("TELEGRAM_STAFF_CHAT_ID")
        if not staff_chat:
            return

        thread_id = None
        try:
            from condo_jev.topic_manager import topic_manager
            thread_id = topic_manager.get_thread_id_for_category(wo.category)
        except Exception:
            pass

        def _send() -> None:
            send_telegram_direct_message(
                chat_id=staff_chat,
                text=text,
                reply_markup=markup,
                message_thread_id=thread_id,
            )

        th = threading.Thread(target=_send, daemon=True)
        th.start()

    def create_work_order(
        self,
        request: ResidentRequest,
        classification: Classification,
        resident_id: str,
        resident_username: str | None = None,
        resident_name: str | None = None,
        photo_path: str | None = None,
        attachment_filename: str | None = None,
        resident_chat_id: str | None = None,
        notify_staff: bool = True,
    ) -> WorkOrder:
        """Create and persist a new Work Order from a classified resident request."""
        now_iso = datetime.now(timezone.utc).isoformat()
        comms = build_follow_up_and_dispatch(request, classification)

        with self._lock:
            records = self._read_records()
            next_num = 1041 + len(records)
            ticket_id = f"EST-{next_num}"
            work_order_id = f"WO-{ticket_id}"

            if classification.priority == Priority.EMERGENCY:
                status = WorkOrderStatus.EMERGENCY_ESCALATION.value
            elif classification.needs_human_review:
                status = WorkOrderStatus.PENDING_REVIEW.value
            else:
                status = WorkOrderStatus.AUTO_DISPATCHED.value

            resolved_location = classification.extracted_location or request.location
            comp = extract_estate_components(request.text, resolved_location)
            resolved_block = comp.block
            resolved_level = comp.level
            resolved_unit = comp.unit
            resolved_reason = comp.reason or request.text
            if not resolved_location and comp.formatted_location:
                resolved_location = comp.formatted_location

            resolved_chat_id = resident_chat_id
            if not resolved_chat_id and (resident_id.isdigit() or (resident_id.startswith("-") and resident_id[1:].isdigit())):
                resolved_chat_id = resident_id

            wo = WorkOrder(
                work_order_id=work_order_id,
                ticket_id=ticket_id,
                created_at=now_iso,
                updated_at=now_iso,
                channel=request.channel,
                resident_id=str(resident_id),
                resident_username=resident_username,
                resident_name=resident_name,
                resident_chat_id=resolved_chat_id,
                photo_path=photo_path,
                attachment_filename=attachment_filename or (Path(photo_path).name if photo_path else None),
                text=request.text,
                category=classification.category,
                category_title=classification.category_title,
                assigned_team=classification.assigned_team,
                priority=classification.priority,
                urgency_score=classification.urgency_score,
                choice_confidence=classification.choice_confidence,
                sla_target=classification.sla_target,
                location=resolved_location,
                block=resolved_block,
                level=resolved_level,
                unit=resolved_unit,
                issue_reason=resolved_reason,
                status=status,
                needs_human_review=classification.needs_human_review,
                review_reasons=list(classification.review_reasons),
                missing_details=list(classification.missing_details),
                evidence_quotes=list(classification.evidence_quotes),
                dispatch_brief=comms["dispatch_brief"],
                resident_reply=comms["resident_reply"],
                notes=[],
                dispatched_at=now_iso if status == WorkOrderStatus.AUTO_DISPATCHED.value else None,
            )

            records.insert(0, wo.model_dump())
            self._write_records(records)

        self._trigger_webhook_async("work_order.created", wo)
        if notify_staff:
            self._notify_staff_async(wo, format_staff_dispatch_alert(wo), build_staff_alert_markup(wo))
        return wo

    def get(self, query_id: str) -> WorkOrder | None:
        """Find a work order by Work Order ID or Ticket ID (case-insensitive)."""
        clean_id = query_id.strip().upper().replace("#", "")
        with self._lock:
            for rec in self._read_records():
                w_id = str(rec.get("work_order_id", "")).upper()
                t_id = str(rec.get("ticket_id", "")).upper()
                if (
                    clean_id == w_id
                    or clean_id == t_id
                    or clean_id in (w_id.replace("WO-", ""), t_id.replace("EST-", ""))
                    or (clean_id.isdigit() and clean_id in t_id)
                ):
                    return WorkOrder.model_validate(rec)
        return None

    def list_all(self, limit: int = 200) -> list[WorkOrder]:
        """List all work orders, newest first."""
        with self._lock:
            records = self._read_records()
            return [WorkOrder.model_validate(r) for r in records[:limit]]

    def list_for_resident(self, resident_id: str, limit: int = 50) -> list[WorkOrder]:
        """List work orders submitted by a specific resident (e.g. Telegram chat ID)."""
        clean_id = str(resident_id).strip()
        with self._lock:
            results = []
            for r in self._read_records():
                if str(r.get("resident_id", "")).strip() == clean_id or str(r.get("resident_chat_id", "")).strip() == clean_id:
                    results.append(WorkOrder.model_validate(r))
                if len(results) >= limit:
                    break
            return results

