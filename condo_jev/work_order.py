    def clear_mock_work_orders(self) -> int:
        """Remove all mock/simulated tickets, retaining only genuine resident work orders sent on Telegram."""
        with self._lock:
            records = self._read_records()
            real_records = [
                r for r in records
                if r.get("channel") == "Telegram" and str(r.get("resident_id", "")).isdigit()
            ]
            removed = len(records) - len(real_records)
            self._write_records(real_records)
            return removed

