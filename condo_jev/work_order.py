    def update_location(self, query_id: str, location: str) -> WorkOrder | None:
        """Update location for a work order (e.g. when resident replies with their unit)."""
        clean_id = query_id.strip().upper().replace("#", "")
        now_iso = datetime.now(timezone.utc).isoformat()
        target_wo: WorkOrder | None = None
        with self._lock:
            records = self._read_records()
            for i, rec in enumerate(records):
                w_id = str(rec.get("work_order_id", "")).upper()
                t_id = str(rec.get("ticket_id", "")).upper()
                if clean_id in (w_id, t_id, w_id.replace("WO-", ""), t_id.replace("EST-", "")):
                    loc_clean = location.strip()
                    rec["location"] = loc_clean
                    comp = extract_estate_components(rec.get("text", ""), loc_clean)
                    if comp.block:
                        rec["block"] = comp.block
                    if comp.level:
                        rec["level"] = comp.level
                    if comp.unit:
                        rec["unit"] = comp.unit
                    if comp.reason and comp.reason != loc_clean:
                        rec["issue_reason"] = comp.reason
                    rec["updated_at"] = now_iso
                    rec.setdefault("notes", []).append(f"[{now_iso}] Resident provided location: {loc_clean}")
                    if "missing_details" in rec:
                        rec["missing_details"] = [
                            d for d in rec["missing_details"] if "location" not in d.lower() and "unit" not in d.lower()
                        ]
                    records[i] = rec
                    self._write_records(records)
                    target_wo = WorkOrder.model_validate(rec)
                    break

        if target_wo:
            self._trigger_webhook_async("work_order.updated", target_wo)
        return target_wo

