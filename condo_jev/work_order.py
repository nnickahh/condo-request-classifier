    def delete_work_order(self, query_id: str) -> bool:
        """Permanently delete a work order by work_order_id, ticket_id, or numeric ID."""
        clean_id = query_id.strip().upper().replace("#", "")
        deleted = False
        target_rec: dict[str, Any] | None = None
        with self._lock:
            records = self._read_records()
            new_records = []
            for rec in records:
                w_id = str(rec.get("work_order_id", "")).upper()
                t_id = str(rec.get("ticket_id", "")).upper()
                if clean_id in (w_id, t_id, w_id.replace("WO-", ""), t_id.replace("EST-", "")):
                    deleted = True
                    target_rec = rec
                else:
                    new_records.append(rec)
            if deleted:
                self._write_records(new_records)
        if target_rec:
            photo = target_rec.get("photo_path")
            if photo and os.path.exists(photo):
                try:
                    os.remove(photo)
                except OSError:
                    pass
        return deleted

    def bulk_delete_work_orders(self, query_ids: list[str]) -> int:
        """Permanently delete multiple work orders by their IDs."""
        clean_ids = {qid.strip().upper().replace("#", "") for qid in query_ids if qid and qid.strip()}
        if not clean_ids:
            return 0
        deleted_count = 0
        deleted_photos: list[str] = []
        with self._lock:
            records = self._read_records()
            new_records = []
            for rec in records:
                w_id = str(rec.get("work_order_id", "")).upper()
                t_id = str(rec.get("ticket_id", "")).upper()
                keys = {w_id, t_id, w_id.replace("WO-", ""), t_id.replace("EST-", "")}
                if clean_ids.intersection(keys):
                    deleted_count += 1
                    photo = rec.get("photo_path")
                    if photo:
                        deleted_photos.append(photo)
                else:
                    new_records.append(rec)
            if deleted_count > 0:
                self._write_records(new_records)
        for photo in deleted_photos:
            if photo and os.path.exists(photo):
                try:
                    os.remove(photo)
                except OSError:
                    pass
        return deleted_count

