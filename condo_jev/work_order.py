class WorkOrder(StrictModel):
    """
    Structured Work Order entity generated by the Condo Management Agent.
    Bridges resident intake (Telegram, App, Web) to estate department dispatch.
    """

    model_config = ConfigDict(extra="ignore", str_strip_whitespace=True)

    work_order_id: str
    ticket_id: str
    created_at: str
    updated_at: str
    channel: str = "Telegram"
    resident_id: str
    resident_username: str | None = None
    resident_name: str | None = None
    text: str
    category: Category
    category_title: str
    assigned_team: str
    priority: Priority
    urgency_score: float = Field(ge=0.0, le=1.0)
    choice_confidence: float = Field(ge=0.0, le=1.0)
    sla_target: str
    location: str | None = None
    status: str = WorkOrderStatus.AUTO_DISPATCHED.value
    needs_human_review: bool = False
    review_reasons: list[str] = Field(default_factory=list)
    missing_details: list[str] = Field(default_factory=list)
    evidence_quotes: list[str] = Field(default_factory=list)
    dispatch_brief: str
    resident_reply: str
    notes: list[str] = Field(default_factory=list)

    # CMMS Extensions
    assigned_technician: str | None = None
    technician_phone: str | None = None
    technician_vendor: str | None = None
    resolution_summary: str | None = None
    parts_or_materials: list[str] = Field(default_factory=list)
    labor_hours: float | None = None
    cost_sgd: float | None = None
    dispatched_at: str | None = None
    resolved_at: str | None = None
    closed_at: str | None = None

    # Telegram & Evidence Integration
    photo_path: str | None = None
    attachment_filename: str | None = None
    resident_chat_id: str | None = None
    resident_feedback_rating: int | None = None
    resident_feedback_comment: str | None = None
    reopened_count: int = 0

    # Categorized Estate Components
    block: str | None = None
    level: str | None = None
    unit: str | None = None
    issue_reason: str | None = None

    # Multi-language & Transcription
    original_text: str | None = None
    detected_language: str | None = None
    is_transcribed_audio: bool = False

    @property
    def display_block(self) -> str:
        if self.block:
            return self.block
        return extract_estate_components(self.text, self.location).block or "—"

    @property
    def display_level(self) -> str:
        if self.level:
            return self.level
        return extract_estate_components(self.text, self.location).level or "—"

    @property
    def display_unit(self) -> str:
        if self.unit:
            return self.unit
        return extract_estate_components(self.text, self.location).unit or "—"

    @property
    def display_reason(self) -> str:
        if self.issue_reason:
            return self.issue_reason
        return extract_estate_components(self.text, self.location).reason or self.text


def send_telegram_direct_message(
    chat_id: str | int,
    text: str,
    reply_markup: dict[str, Any] | None = None,
    token: str | None = None,
    timeout: float = 20.0,
    message_thread_id: int | None = None,
) -> dict[str, Any]:
    """
    Synchronously deliver a message to a Telegram chat using HTTP POST.
    Thread-safe and callable directly from Streamlit UI, REST API, or worker threads.
    Supports topic threads via message_thread_id or chat_id formatted as '<chat_id>_<thread_id>'.
    Returns: {"success": bool, "result": Any, "error": str | None}
    """
    bot_token = token or os.getenv("TELEGRAM_BOT_TOKEN")
    if not bot_token:
        return {"success": False, "error": "No TELEGRAM_BOT_TOKEN configured"}

    clean_chat_id = str(chat_id).strip()
    if clean_chat_id.startswith("tg_"):
        clean_chat_id = clean_chat_id.replace("tg_", "")

    # Parse compound chat_id_thread_id format (e.g. copied from web URL: -1003561028399_10)
    if "_" in clean_chat_id and not clean_chat_id.startswith("@"):
        parts = clean_chat_id.split("_", 1)
        clean_chat_id = parts[0]
        if message_thread_id is None and parts[1].isdigit():
            message_thread_id = int(parts[1])

    # Skip simulated / non-live IDs (e.g. mock IDs in tests)
    is_valid_chat_id = (
        clean_chat_id.isdigit()
        or (clean_chat_id.startswith("-") and clean_chat_id[1:].isdigit())
        or clean_chat_id.startswith("@")
    )
    if not is_valid_chat_id:
        return {"success": False, "error": f"Simulated or non-numeric Telegram chat ID: {chat_id}"}

    # Mute live outbound Telegram network requests during automated tests
    import sys
    if (
        os.getenv("PYTEST_CURRENT_TEST")
        or "pytest" in sys.modules
        or os.getenv("CONDO_TEST_MODE") == "1"
    ) and not os.getenv("CONDO_FORCE_LIVE_TELEGRAM"):
        return {"success": True, "result": {"message_id": 999999}, "simulated": True}

    url = f"https://api.telegram.org/bot{bot_token}/sendMessage"
    payload: dict[str, Any] = {
        "chat_id": clean_chat_id,
        "text": text,
        "parse_mode": "Markdown",
    }
    if message_thread_id is not None:
        payload["message_thread_id"] = int(message_thread_id)
    if reply_markup:
        payload["reply_markup"] = reply_markup

    data_bytes = json.dumps(payload, ensure_ascii=False).encode("utf-8")
    req = urllib.request.Request(
        url,
        data=data_bytes,
        headers={"Content-Type": "application/json; charset=utf-8"},
        method="POST",
    )
    try:
        with urllib.request.urlopen(req, timeout=timeout) as resp:
            resp_data = json.loads(resp.read().decode("utf-8"))
            return {"success": bool(resp_data.get("ok")), "result": resp_data.get("result"), "error": None}
    except urllib.error.HTTPError as exc:
        err_body = exc.read().decode("utf-8", errors="replace")
        # If Markdown entity parsing failed or thread not found, retry safely
        modified = False
        if "can't parse entities" in err_body:
            payload.pop("parse_mode", None)
            modified = True
        if "message thread not found" in err_body or "thread not found" in err_body:
            payload.pop("message_thread_id", None)
            modified = True
        if modified or exc.code == 400:
            payload.pop("parse_mode", None)
            payload.pop("message_thread_id", None)
            retry_bytes = json.dumps(payload, ensure_ascii=False).encode("utf-8")
            retry_req = urllib.request.Request(
                url,
                data=retry_bytes,
                headers={"Content-Type": "application/json; charset=utf-8"},
                method="POST",
            )
            try:
                with urllib.request.urlopen(retry_req, timeout=timeout) as r2:
                    resp_data2 = json.loads(r2.read().decode("utf-8"))
                    return {"success": bool(resp_data2.get("ok")), "result": resp_data2.get("result"), "error": None}
            except Exception as e2:
                return {"success": False, "error": f"{exc}: {err_body} (retry error: {e2})"}
        return {"success": False, "error": f"HTTP {exc.code}: {err_body}"}
    except Exception as exc:
        return {"success": False, "error": str(exc)}


