    def get_cmms_stats(self) -> dict[str, Any]:
        """Compute CMMS operational KPIs and metrics across all work orders."""
        orders = self.list_all(limit=500)
        total = len(orders)
        if total == 0:
            return {
                "total_work_orders": 0,
                "open_work_orders": 0,
                "in_progress": 0,
                "pending_review": 0,
                "assigned": 0,
                "resolved": 0,
                "closed": 0,
                "emergency": 0,
                "avg_confidence": 0.0,
                "by_department": {},
                "by_priority": {},
                "by_status": {},
            }

        open_statuses = {
            WorkOrderStatus.AUTO_DISPATCHED.value,
            WorkOrderStatus.PENDING_REVIEW.value,
            WorkOrderStatus.EMERGENCY_ESCALATION.value,
            WorkOrderStatus.STAFF_APPROVED.value,
            WorkOrderStatus.ASSIGNED.value,
            WorkOrderStatus.IN_PROGRESS.value,
            WorkOrderStatus.PENDING_PARTS.value,
        }

        open_count = sum(1 for o in orders if o.status in open_statuses)
        in_prog_count = sum(1 for o in orders if o.status in (WorkOrderStatus.IN_PROGRESS.value, WorkOrderStatus.ASSIGNED.value, WorkOrderStatus.PENDING_PARTS.value))
        pending_review_count = sum(1 for o in orders if "Review" in o.status or o.needs_human_review)
        assigned_count = sum(1 for o in orders if o.assigned_technician is not None or o.status == WorkOrderStatus.ASSIGNED.value)
        resolved_count = sum(1 for o in orders if o.status in (WorkOrderStatus.RESOLVED.value, WorkOrderStatus.CLOSED.value, "Resolved", "Closed"))
        closed_count = sum(1 for o in orders if o.status in (WorkOrderStatus.CLOSED.value, "Closed"))
        emerg_count = sum(1 for o in orders if o.priority == Priority.EMERGENCY)
        avg_conf = sum(o.choice_confidence for o in orders) / total

        dept_counts: dict[str, int] = {}
        prio_counts: dict[str, int] = {}
        status_counts: dict[str, int] = {}

        for o in orders:
            dept_counts[o.category_title] = dept_counts.get(o.category_title, 0) + 1
            prio_counts[str(o.priority.value).upper()] = prio_counts.get(str(o.priority.value).upper(), 0) + 1
            status_counts[o.status] = status_counts.get(o.status, 0) + 1

        return {
            "total_work_orders": total,
            "open_work_orders": open_count,
            "in_progress": in_prog_count,
            "pending_review": pending_review_count,
            "assigned": assigned_count,
            "resolved": resolved_count,
            "closed": closed_count,
            "emergency": emerg_count,
            "avg_confidence": round(avg_conf, 4),
            "by_department": dept_counts,
            "by_priority": prio_counts,
            "by_status": status_counts,
        }

